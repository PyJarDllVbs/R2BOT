void PowerInit(void)
{
    //初始化四轮电机
    HAL_TIM_PWM_Start(&htim3,TIM_CHANNEL_1);
    HAL_TIM_PWM_Start(&htim3,TIM_CHANNEL_2);
    HAL_TIM_PWM_Start(&htim3,TIM_CHANNEL_3);
    HAL_TIM_PWM_Start(&htim3,TIM_CHANNEL_4);
    //初始化丝杠电机
    HAL_TIM_PWM_Start(&htim4,TIM_CHANNEL_1);
    HAL_TIM_PWM_Start(&htim4,TIM_CHANNEL_2);
    //初始化舵机电机（初始-90）
    HAL_TIM_PWM_Start(&htim1,TIM_CHANNEL_1);
    __HAL_TIM_SET_COMPARE(&htim1,TIM_CHANNEL_1,minsteer);
    HAL_TIM_PWM_Start(&htim1,TIM_CHANNEL_2);
    __HAL_TIM_SET_COMPARE(&htim1,TIM_CHANNEL_2,minsteer);
}

void wheelpush(void)
{
    if(pwm.brake)//刹车处理，in置高，且将pwm置0
    {
        HAL_GPIO_WritePin(Wh0in1_GPIO_Port,Wh0in1_Pin,GPIO_PIN_SET);
        HAL_GPIO_WritePin(Wh0in2_GPIO_Port,Wh0in2_Pin,GPIO_PIN_SET);
        __HAL_TIM_SET_COMPARE(&htim3,TIM_CHANNEL_1,0);
        HAL_GPIO_WritePin(Wh1in1_GPIO_Port,Wh1in1_Pin,GPIO_PIN_SET);
        HAL_GPIO_WritePin(Wh1in2_GPIO_Port,Wh1in2_Pin,GPIO_PIN_SET);
        __HAL_TIM_SET_COMPARE(&htim3,TIM_CHANNEL_2,0);
        HAL_GPIO_WritePin(Wh2in1_GPIO_Port,Wh2in1_Pin,GPIO_PIN_SET);
        HAL_GPIO_WritePin(Wh2in2_GPIO_Port,Wh2in2_Pin,GPIO_PIN_SET);
        __HAL_TIM_SET_COMPARE(&htim3,TIM_CHANNEL_3,0);
        HAL_GPIO_WritePin(Wh3in1_GPIO_Port,Wh3in1_Pin,GPIO_PIN_SET);
        HAL_GPIO_WritePin(Wh3in2_GPIO_Port,Wh3in2_Pin,GPIO_PIN_SET);
        __HAL_TIM_SET_COMPARE(&htim3,TIM_CHANNEL_4,0);
        return;
    }
    //轮子0
    if(pwm.wheel[0]>0)
    {
        HAL_GPIO_WritePin(Wh0in1_GPIO_Port,Wh0in1_Pin,GPIO_PIN_RESET);
        HAL_GPIO_WritePin(Wh0in2_GPIO_Port,Wh0in2_Pin,GPIO_PIN_SET);
    }
    if(pwm.wheel[0]==0)
    {
        HAL_GPIO_WritePin(Wh0in1_GPIO_Port,Wh0in1_Pin,GPIO_PIN_RESET);
        HAL_GPIO_WritePin(Wh0in2_GPIO_Port,Wh0in2_Pin,GPIO_PIN_RESET);
    }
    if(pwm.wheel[0]<0)
    {
        HAL_GPIO_WritePin(Wh0in1_GPIO_Port,Wh0in1_Pin,GPIO_PIN_SET);
        HAL_GPIO_WritePin(Wh0in2_GPIO_Port,Wh0in2_Pin,GPIO_PIN_RESET);
    }
    __HAL_TIM_SET_COMPARE(&htim3,TIM_CHANNEL_1,abs(pwm.wheel[0]));
    //轮子1
    if(pwm.wheel[1]>0)
    {
        HAL_GPIO_WritePin(Wh1in1_GPIO_Port,Wh1in1_Pin,GPIO_PIN_SET);
        HAL_GPIO_WritePin(Wh1in2_GPIO_Port,Wh1in2_Pin,GPIO_PIN_RESET);
    }
    if(pwm.wheel[1]==0)
    {
        HAL_GPIO_WritePin(Wh1in1_GPIO_Port,Wh1in1_Pin,GPIO_PIN_RESET);
        HAL_GPIO_WritePin(Wh1in2_GPIO_Port,Wh1in2_Pin,GPIO_PIN_RESET);
    }
    if(pwm.wheel[1]<0)
    {
        HAL_GPIO_WritePin(Wh1in1_GPIO_Port,Wh1in1_Pin,GPIO_PIN_RESET);
        HAL_GPIO_WritePin(Wh1in2_GPIO_Port,Wh1in2_Pin,GPIO_PIN_SET);
    }
    __HAL_TIM_SET_COMPARE(&htim3,TIM_CHANNEL_2,abs(pwm.wheel[1]));
    //轮子2
    if(pwm.wheel[2]>0)
    {
        HAL_GPIO_WritePin(Wh2in1_GPIO_Port,Wh2in1_Pin,GPIO_PIN_RESET);
        HAL_GPIO_WritePin(Wh2in2_GPIO_Port,Wh2in2_Pin,GPIO_PIN_SET);
    }
    if(pwm.wheel[2]==0)
    {
        HAL_GPIO_WritePin(Wh2in1_GPIO_Port,Wh2in1_Pin,GPIO_PIN_RESET);
        HAL_GPIO_WritePin(Wh2in2_GPIO_Port,Wh2in2_Pin,GPIO_PIN_RESET);
    }
    if(pwm.wheel[2]<0)
    {
        HAL_GPIO_WritePin(Wh2in1_GPIO_Port,Wh2in1_Pin,GPIO_PIN_SET);
        HAL_GPIO_WritePin(Wh2in2_GPIO_Port,Wh2in2_Pin,GPIO_PIN_RESET);
    }
    __HAL_TIM_SET_COMPARE(&htim3,TIM_CHANNEL_3,abs(pwm.wheel[2]));
    //轮子3
    if(pwm.wheel[3]>0)
    {
        HAL_GPIO_WritePin(Wh3in1_GPIO_Port,Wh3in1_Pin,GPIO_PIN_SET);
        HAL_GPIO_WritePin(Wh3in2_GPIO_Port,Wh3in2_Pin,GPIO_PIN_RESET);
    }
    if(pwm.wheel[3]==0)
    {
        HAL_GPIO_WritePin(Wh3in1_GPIO_Port,Wh3in1_Pin,GPIO_PIN_RESET);
        HAL_GPIO_WritePin(Wh3in2_GPIO_Port,Wh3in2_Pin,GPIO_PIN_RESET);
    }
    if(pwm.wheel[3]<0)
    {
        HAL_GPIO_WritePin(Wh3in1_GPIO_Port,Wh3in1_Pin,GPIO_PIN_RESET);
        HAL_GPIO_WritePin(Wh3in2_GPIO_Port,Wh3in2_Pin,GPIO_PIN_SET);
    }
    __HAL_TIM_SET_COMPARE(&htim3,TIM_CHANNEL_4,abs(pwm.wheel[3]));
}
void screwpush(void)
{
    //丝杠0(丝杠不动默认刹车)
    if(pwm.screw[0]>0)
    {
        HAL_GPIO_WritePin(Screw0in1_GPIO_Port,Screw0in1_Pin,GPIO_PIN_RESET);
        HAL_GPIO_WritePin(Screw0in2_GPIO_Port,Screw0in2_Pin,GPIO_PIN_SET);
    }
    if(pwm.screw[0]==0)
    {
        HAL_GPIO_WritePin(Screw0in1_GPIO_Port,Screw0in1_Pin,GPIO_PIN_SET);
        HAL_GPIO_WritePin(Screw0in2_GPIO_Port,Screw0in2_Pin,GPIO_PIN_SET);
    }
    if(pwm.screw[0]<0)
    {
        HAL_GPIO_WritePin(Screw0in1_GPIO_Port,Screw0in1_Pin,GPIO_PIN_SET);
        HAL_GPIO_WritePin(Screw0in2_GPIO_Port,Screw0in2_Pin,GPIO_PIN_RESET);
    }
    __HAL_TIM_SET_COMPARE(&htim4,TIM_CHANNEL_1,maxccr);
    //丝杠1(丝杠不动默认刹车)
    if(pwm.screw[1]>0)
    {
        HAL_GPIO_WritePin(Screw1in1_GPIO_Port,Screw1in1_Pin,GPIO_PIN_RESET);
        HAL_GPIO_WritePin(Screw1in2_GPIO_Port,Screw1in2_Pin,GPIO_PIN_SET);
    }
    if(pwm.screw[1]==0)
    {
        HAL_GPIO_WritePin(Screw1in1_GPIO_Port,Screw1in1_Pin,GPIO_PIN_SET);
        HAL_GPIO_WritePin(Screw1in2_GPIO_Port,Screw1in2_Pin,GPIO_PIN_SET);
    }
    if(pwm.screw[1]<0)
    {
        HAL_GPIO_WritePin(Screw1in1_GPIO_Port,Screw1in1_Pin,GPIO_PIN_SET);
        HAL_GPIO_WritePin(Screw1in2_GPIO_Port,Screw1in2_Pin,GPIO_PIN_RESET);
    }
    __HAL_TIM_SET_COMPARE(&htim4,TIM_CHANNEL_2,maxccr);
}
void clawpush(void)
{
    __HAL_TIM_SET_COMPARE(&htim1,TIM_CHANNEL_1,pwm.claw[0]);
    __HAL_TIM_SET_COMPARE(&htim1,TIM_CHANNEL_2,pwm.claw[1]);
}
void push(void)
{
    if(!ps2.connected)
    {
        HAL_GPIO_WritePin(STBY_GPIO_Port,STBY_Pin,GPIO_PIN_RESET);
    }
    else
    {
        HAL_GPIO_WritePin(STBY_GPIO_Port,STBY_Pin,GPIO_PIN_SET);
    }
    wheelpush();
    screwpush();
    clawpush();
}
